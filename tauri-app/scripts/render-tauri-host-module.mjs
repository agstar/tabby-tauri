import { execFile } from 'node:child_process'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { promisify } from 'node:util'

const execFileAsync = promisify(execFile)

const outputPath = resolve(
  process.cwd(),
  process.argv[2] ?? '../../.omx/plans/tauri-host-module.draft.ts',
)

async function prepareTauriApiStub(outDir) {
  const tauriApiStubDir = join(outDir, 'node_modules', '@tauri-apps', 'api')
  await mkdir(tauriApiStubDir, { recursive: true })
  await writeFile(
    join(tauriApiStubDir, 'package.json'),
    JSON.stringify({
      type: 'module',
      exports: {
        './core': './core.js',
        './window': './window.js',
      },
    }),
  )
  await writeFile(
    join(tauriApiStubDir, 'core.js'),
    [
      'export class Channel {',
      '  constructor () { this.onmessage = undefined }',
      '}',
      'export async function invoke () {',
      '  throw new Error("Tauri invoke stub called while rendering host module")',
      '}',
      '',
    ].join('\n'),
  )
  await writeFile(
    join(tauriApiStubDir, 'window.js'),
    'export function getCurrentWindow () { return { listen: async () => () => {} } }\n',
  )
}

async function compileRegistry(outDir) {
  await writeFile(join(outDir, 'package.json'), '{"type":"module"}\n')
  await execFileAsync(
    process.execPath,
    [
      'node_modules/typescript/bin/tsc',
      '--target',
      'ES2022',
      '--module',
      'NodeNext',
      '--moduleResolution',
      'NodeNext',
      '--lib',
      'ES2022,DOM,DOM.Iterable',
      '--skipLibCheck',
      '--outDir',
      outDir,
      '--rootDir',
      'src',
      'src/tauri-tabby-session-registry.ts',
      'src/tauri-providers.ts',
    ],
    { cwd: process.cwd() },
  )
}

async function main() {
  const outDir = await mkdtemp(join(tmpdir(), 'tabby-tauri-host-module-'))
  try {
    await prepareTauriApiStub(outDir)
    await compileRegistry(outDir)

    const registry = await import(pathToFileURL(join(outDir, 'tauri-tabby-session-registry.js')))
    const source = registry.renderTauriAngularHostModuleSource(
      registry.createTauriAngularModuleBlueprint(true),
    )

    await mkdir(dirname(outputPath), { recursive: true })
    await writeFile(
      outputPath,
      [
        '// Generated by tabby-tauri/scripts/render-tauri-host-module.mjs',
        '// Draft/review artifact: the upstream tabby-tauri package now carries',
        '// the concrete Tauri host-module provider implementation.',
        source,
      ].join('\n'),
    )
    console.log(JSON.stringify({ outputPath, bytes: source.length }, null, 2))
  } finally {
    await rm(outDir, { recursive: true, force: true })
  }
}

await main()
